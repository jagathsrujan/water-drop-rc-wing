  // ------------------------------------------------------------------ rules
  function unmet(it) {
    for (const n of it.needs || []) if (!S.done[n.id]) return n;
    if (it.needs_any) {
      const any = it.needs_any.ids.some((i) => S.done[i]);
      if (!any) {
        const st = STEPS[ITEM[it.id].k];
        const chainStarted = st.items.some((x) => x.needs_any && S.done[x.id]);
        if (!(it.first_ok && !chainStarted)) return { id: it.needs_any.ids[0], type: it.needs_any.type, msg: it.needs_any.msg };
      }
    }
    return null;
  }

  function attempt(id, slotItem) {
    const st = STEPS[S.step];
    const mine = st.items.find((it) => it.id === id);
    if (!mine) return wrongItem(id);
    const n = unmet(mine);
    if (n) return mistake(n.type, `${label(mine, true)}: not yet`, n.msg, fixFor(n));
    const slotMode = st.mode === "slot" && mine.slot !== false;
    if (slotMode) {
      if (!slotItem) { say("info", "Where does it go?", "Click the dashed outline in the view where " + label(mine, true) + " goes."); return; }
      if (slotItem.id !== mine.id) {
        const a = mine.parts[0], b = slotItem.parts[0];
        const twin = P[a] && P[a].mirror === b || mine.id.replace(/-R|R-|L-|-L/, "") === slotItem.id.replace(/-R|R-|L-|-L/, "") && mine.id !== slotItem.id && sideOf(mine.id) && sideOf(mine.id) !== sideOf(slotItem.id);
        if (twin) return mistake("side", `${label(mine, true)} on the ${sideWord(slotItem.id)} side`,
          `That place is for ${label(slotItem, true)}, the ${sideWord(slotItem.id)}-side twin. ${label(mine, true)} is the ${sideWord(mine.id)}-side part (its name ends in ${sideOf(mine.id)}).`,
          `Put ${label(mine, true)} on the ${sideWord(mine.id)} side.`);
        return mistake("place", `${label(mine, true)} in the wrong place`, `That place is for ${label(slotItem, true)}.`, `Find the place of ${label(mine, true)}: ` + placeHint(mine));
      }
    }
    if (mine.orient !== false && mine.kind !== "action") {
      const ref = mine.kind === "group" ? P[mine.hint_from] : P[mine.id];
      if (ref && ref.hint) {
        const o = orientFor(id);
        if (o.flip) return mistake("orient", `${label(mine, true)} is upside down`,
          `The engraved face is down${/^(RO|LO|RI|LI|LAM)/.test(mine.id) ? " (on the side panels the engraved faces must end up INSIDE the pod)" : ""}: you would lose the name and the slot marks, and on a tapered part the bevelled slots face the wrong way.`,
          "Flip it over so the engraving reads normally.");
        if (o.rot) return mistake("orient", `${label(mine, true)} is turned round`,
          `Its arrow '${ref.hint.text}' must point to the ${{ FWD: "nose", UP: "top", LE: "leading edge", TE: "trailing edge" }[ref.hint.kind]}. Turned 180 deg, the tabs and slots do not line up${ref.hint.kind === "LE" ? " and the airfoil is backwards" : ""}.`,
          "Turn it 180 deg so the arrow points the right way.");
      }
    }
    succeed(mine);
  }

  function sideOf(id) {
    const p = P[id];
    if (/^(RO|RI)-/.test(id) || /^LAM-R/.test(id)) return "R";
    if (/^(LO|LI)-/.test(id) || /^LAM-L/.test(id)) return "L";
    const m = id.match(/^WC\d([RL])-|^J2-\d([RL])-|^J3-([RL])-|^TJ1-([RL])|^(?:WF|WR|FSP)-([RL])|-([RL])\d?$|^(?:TR\d|S\dB)([RL])$/);
    if (m) return m.slice(1).find(Boolean);
    return p && p.mirror ? null : null;
  }
  function sideWord(id) { return { R: "right", L: "left" }[sideOf(id)] || "other"; }
  function placeHint(it) {
    const p = P[it.parts[0]];
    if (!p) return "";
    if (/^W-R(\d+)/.test(it.id)) return `rib station Y ${it.id.match(/^W-R(\d+)/)[1]} mm on the ${sideWord(it.id)} wing.`;
    if (p.floor_piece) return `its floor slots are in ${p.floor_piece}.`;
    return "check the engraved names on the neighbouring parts.";
  }
  function fixFor(n) {
    if (n.type === "jig") return `Put ${n.id} in place first (it is on the bench or in the actions).`;
    if (n.type === "pin") return "Do the pin action first: two PIN-6x11 per jig.";
    if (n.type === "neutral") return "Centre the servo and set the surface to 0 deg first.";
    if (n.type === "safety") return "Do the safe step first.";
    return `Do ${ITEM[n.id] ? label(ITEM[n.id].it, true) : n.id} first.`;
  }

  function wrongItem(id) {
    const st = STEPS[S.step];
    const other = ITEM[id] || (PART_ITEM[id] ? ITEM[PART_ITEM[id]] : null);
    // the twin of a part this step needs?
    const twinOf = st.items.find((it) => (it.parts || []).some((p) => P[p] && P[p].mirror === id));
    if (twinOf) return mistake("side", `${id} is the wrong side`,
      `${id} is the ${sideWord(id)}-side part; this step builds the ${sideWord(twinOf.id)} side (${twinOf.id}). The L and R parts are mirror images: the tabs, slots and engraved arrows only match on their own side.`,
      `Put ${id} back; use ${twinOf.id}.`);
    if (other) {
      const k = other.k, it = other.it;
      if (S.done[it.id]) return mistake("placed", `${id} is already built in`, `${id} went in at step ${k + 1}.`, "Pick another part.");
      const n = unmet(it);
      const why = n ? " " + n.msg : "";
      const msg = k > S.step ? `${label(it, true)} belongs to step ${k + 1}, "${STEPS[k].title}".${why}` : `${label(it, true)} is not part of this step.`;
      return mistake(k > S.step ? "order" : "part", `${label(it, true)}: wrong part for now`, msg, "Put it back on the bench and finish this step first.");
    }
    return mistake("part", `${id}: wrong part`, `${id} is not used in this step.`, "Put it back.");
  }

  function action(a) {
    if (a.kind === "trap") {
      const t = a.trap;
      S.done[a.id] = true;    // a trap is shown once
      return mistake(t.type === "trap" ? "trap" : t.type, t.label, t.mistake, t.fix);
    }
    const it = ITEM[a.id].it;
    if (it.kind === "neutral") return openNeutral(it);
    const n = unmet(it);
    if (n) return mistake(n.type, `${it.label}: not yet`, n.msg, fixFor(n));
    succeed(it);
  }

