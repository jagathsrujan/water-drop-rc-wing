"""P6: margins from the SOLIDWORKS Simulation results (cases/*_result.json) -> margins.md.
    python design/simulation/structure/margins.py
Allowables: the P1/P2 design values (design/optimisation/P2_lightening.m; R1 = Wood Handbook FPL-GTR-190), 5th
percentile = mean x (1 - 1.645 CoV), balsa at the design density 0.12 g/cm3 (k = 0.12 / 0.16 = 0.75):
  balsa: bending f = 21.6 k p5(0.16), across the grain fT = 0.04 f (Hankinson Q/P 0.04, estimate), compression
         parallel c = 14.9 k p5(0.18), shear s = 2.1 k p5(0.14);
  birch veneer (paper birch, R1 Table 5-3a): f = 85 p5(0.16), fT = 0.04 f;
  carbon strip: compression 200 MPa (R3, TDS lower bound).
Margin = allowable / |stress| at the ultimate load (the loads already include the 1.5 factor)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
C = os.path.join(HERE, "cases")
p5 = lambda cov: 1 - 1.645 * cov
k = 0.12 / 0.16
BAL = dict(f=21.6 * k * p5(0.16), c=14.9 * k * p5(0.18), s=2.1 * k * p5(0.14))
BAL["fT"] = 0.04 * BAL["f"]
BIR = dict(f=85 * p5(0.16))
BIR["fT"] = 0.04 * BIR["f"]
CARB_C = 200.0


def load(name):
    p = os.path.join(C, name + "_result.json")
    if not os.path.exists(p):
        return None
    r = json.load(open(p))
    return r if r.get("probes") else None


def probe(r, start):
    for p in r["probes"]:
        if p["label"].startswith(start):
            return p
    raise KeyError(start)


def peak(p):
    return max(abs(p["min"]), abs(p["max"]))


def main():
    out = ["# P6 — FEA margins (generated by `margins.py`)", "",
           "Allowables (MPa, 5th percentile, balsa at 0.12 g/cm³): balsa bending %.2f, across the grain %.3f, "
           "compression %.2f, shear %.2f; birch veneer %.1f, across %.2f; carbon compression %.0f." % (
               BAL["f"], BAL["fT"], BAL["c"], BAL["s"], BIR["f"], BIR["fT"], CARB_C), ""]
    # ---- wing box
    r, rc = load("wingbox_n6"), load("wingbox_n6_h25")
    if r:
        case = json.load(open(os.path.join(C, "wingbox_n6.json")))
        L, z = case["hand"]["L_mm"], 50.0
        sc = (L / (L - z)) ** 2                      # uniform load: root moment / moment at z = 50
        rows = [("carbon top cap, compression", "carbon top cap SZ, z", CARB_C),
                ("balsa top cap, compression", "balsa top cap SZ, z", BAL["c"]),
                ("D-box top skin, compression", "D-box top skin SZ, z", BAL["c"]),
                ("front web, shear (web alone)", "front web TYZ", BAL["s"])]
        out += ["## Wing box, n = 6 ultimate (%.1f N per half wing, uniform)" % case["hand"]["load_N"], "",
                "Mesh 2.0 mm (%d elements); 2.5 mm check in brackets. Stresses in the beam region (y > 50 mm) are scaled "
                "to the root by the moment ratio %.3f; the peaks on the clamped root face are a boundary artefact (the "
                "real wing is continuous through the centre section) and are not used." % (r["elements"], sc), "",
                "| Location | FEA y > 50 (MPa) | At the root (MPa) | Allowable | **Margin** |", "|---|---|---|---|---|"]
        for lab, key, allow in rows:
            p = probe(r, key)
            v = peak(p)
            vr = v if "web" in lab else v * sc
            chk = " (%.2f)" % peak(probe(rc, key)) if rc else ""
            out.append("| %s | %.2f%s | %.2f | %.2f | **%.2f** |" % (lab, v, chk, vr, allow, allow / vr))
        tip = probe(r, "tip UY, carbon")["max"]
        out += ["", "Tip deflection at n = 6: %.1f mm (spar), so about %.1f mm at 1 g." % (tip, tip / 6.0), ""]
    # ---- side panels
    for nm, title, p2 in (("side_panel_grip", "Pod side, grip zone (balsa 1.5 + birch 1.5)", 2.09),
                          ("side_panel_side", "Pod side outside the grip zone (balsa 1.5 + balsa 1.5 crossed)", 1.28)):
        r = load(nm)
        if not r:
            continue
        out += ["## %s, 30 N finger squeeze (ultimate), edges clamped" % title, "",
                "| Layer, stress | FEA peak (MPa) | Allowable | **Margin** |", "|---|---|---|---|"]
        worst = 9e9
        for p in r["probes"]:
            if "stress" not in p["label"]:
                continue
            birch = "birch" in p["label"]
            allow = (BIR if birch else BAL)["fT" if "across" in p["label"] else "f"]
            m = allow / peak(p)
            worst = min(worst, m)
            out.append("| %s | %.2f | %.2f | **%.2f** |" % (p["label"].replace(" (MPa)", ""), peak(p), allow, m))
        d = probe(r, "centre UZ")
        out += ["", "First-ply margin %.2f (P2 hand, simply supported Navier: %.2f); centre deflection %.2f mm." % (
            worst, p2, max(abs(d["min"]), abs(d["max"]))), ""]
    # ---- front stop: sheet-layer stresses on the two outer faces -> stresses in the outer veneer (same strain)
    for nm in ("front_stop_2sheet", "front_stop_nose_in_3sheet"):
        r = load(nm)
        if not r:
            continue
        cj = nm if nm != "front_stop_2sheet" else "front_stop_nose_in"
        case = json.load(open(os.path.join(C, cj + ".json")))
        h = case["hand"]
        n = h.get("sheets", 2)
        grain = {b["name"]: ("X" if "grain X" in b["material"]["name"] else "Y") for b in case["bodies"] if b["name"].startswith("FS-S")}
        out += ["## Front stop FS, nose-in 10 g (%.0f N ultimate), %d x 1.5 birch, crossed, 14 mm spokes, window corners r 2, "
                "edges glued" % (h["load_N"], n), "",
                "| Outer face | Face veneer stress along its grain (MPa) | Margin (f %.1f) | Across its grain (MPa) | "
                "Margin (fT %.2f, first ply) |" % (BIR["f"], BIR["fT"]), "|---|---|---|---|---|"]
        worst_l = worst_t = 9e9
        for k in (1, n):
            g = grain["FS-S%d" % k]
            sx = [p for p in r["probes"] if p["label"].startswith("S%d face" % k) and "SX" in p["label"]][0]
            sy = [p for p in r["probes"] if p["label"].startswith("S%d face" % k) and "SY" in p["label"]][0]
            along, across = (sx, sy) if g == "X" else (sy, sx)
            sl = peak(along) * h["E_L"] / h["E_face"]
            st = peak(across) * h["E_T"] / h["E_cross"]
            worst_l, worst_t = min(worst_l, BIR["f"] / sl), min(worst_t, BIR["fT"] / st)
            out.append("| sheet %d (face grain %s) | %.1f | **%.2f** | %.1f | %.2f |" % (k, g, sl, BIR["f"] / sl, st, BIR["fT"] / st))
        d = probe(r, "ring UZ")
        out += ["", "Along the grain: margin %.2f. Across the grain (cross-ply cracking, 0.04 x MOR, very conservative "
                "for plywood): %.2f. Ring deflection %.2f mm. P2 hand (4 equal spokes, nominal beam stress): 1.57." % (
                    worst_l, worst_t, max(abs(d["min"]), abs(d["max"]))), ""]
    open(os.path.join(HERE, "margins.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
