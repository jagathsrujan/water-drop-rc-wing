CAD = P.CAD
IMG = os.path.join(CAD, "img") + "/"
os.makedirs(IMG, exist_ok=True)
os.makedirs(os.path.join(CAD, "stl"), exist_ok=True)

# ---- checks + csv ----
C.EXTRA_G = {"M2 hatch screws 8 x 0.15 g": 1.2, "CA hinges 8 x 0.1 g": 0.8}
C.stage_b_checks()
bad, total = C.run("3")

# ---- mass table md ----
rows = list(csv.DictReader(open(os.path.join(CAD, "mass_table_stage3.csv"))))
rows = [r for r in rows if r["part"] != "TOTAL"]
import shutil
shutil.copy(os.path.join(CAD, "mass_table_stage3.csv"), os.path.join(CAD, "mass_table.csv"))
rules = [("^Foam_", "XPS 30 foam blocks, hollow (7 mm walls)"), ("^Plate_", "Face plates 1.5 mm light (14)"),
         ("^HalfRib_", "Half ribs 1.5 mm light (4)"), ("^Caps_", "Cap strips on the half ribs"),
         ("^LE_\\d", "LE, printed PLA, 5 segments (fill 0.50)"), ("^LE_Keys|^LE_Joiners", "LE keys + joiners, printed PLA (solid)"),
         ("^TE_", "TE, printed PLA, fixed bays (fill 0.85)"), ("^DBox", "D-box sheeting 1.5 mm"), ("^CSheet", "Bottom centre sheeting 1.5 mm"),
         ("^SparCarbon", "Spar caps, carbon 0.5 x 6"), ("^SparBalsa", "Spar caps, balsa 3 x 6"), ("^ShearWeb", "Shear webs 1.5 mm"),
         ("^FalseSpar", "False spar 3 mm"), ("^TipCap", "Tip cap rings 3 mm"), ("^Ail_LE", "Aileron LE"),
         ("^Ail_Ribs|^Ail_HornRib", "Aileron ribs + horn ribs"), ("^Ail_TE", "Aileron TE wedges"),
         ("^ServoFrame", "Servo frames (PETG)"), ("^ServoHatch", "Servo hatches + lugs (PETG)"), ("^Horn", "Horns (PETG)"),
         ("^RubPlate", "Band rub plates (PETG)"), ("^Pushrod", "Pushrods 1.2 mm steel"), ("^Film", "Film covering"),
         ("^Glue", "Glue (estimate)"), ("screws", "M2 hatch screws"), ("hinges", "CA hinges")]
grp = collections.OrderedDict()
for r in rows:
    g = next((g for pat, g in rules if re.search(pat, r["part"])), r["part"])
    e = grp.setdefault(g, [0, 0.0, set()])
    e[0] += 1; e[1] += float(r["mass_g"]); e[2].add("%s %s" % (r["material"], r["density_kg_m3_or_gsm"]))
pla = sum(float(r["mass_g"]) for r in rows if r["material"] == "pla")
te_pla = sum(float(r["mass_g"]) for r in rows if r["part"].startswith("TE_"))
te_vol_solid = sum(float(r["volume_cm3"]) for r in rows if r["part"].startswith("TE_"))
servo = 2 * 13.4 + 0.6
REVA = 156.6
EMPTY_A = 440.0 + REVA
V_A, LOAD_A = 8.86, 1593.0          # rev A loaded stall with tail download, rho 1.05 (wing_lift_performance.txt)


def line(label, m):
    dm = m - REVA
    e = 440.0 + m
    sc = 996.0 * 100.0 / e
    vs = V_A * ((LOAD_A + dm) / LOAD_A) ** 0.5
    return "| %s | %.1f | %+.1f | %.0f | %.1f | %+.1f %% | %.2f | %s |" % (label, m, dm, e, sc, 100 * (sc / (996.0 * 100 / EMPTY_A) - 1), vs,
                                                                     "pass" if vs <= 9.0 + 1e-9 else "fail")


asa = total - pla + pla * 700.0 / 1240.0
lw = total - pla + pla * 550.0 / 1240.0
te_balsa = te_vol_solid * 0.160                      # hard balsa, solid
lite = total - pla + (pla - te_pla) * 700.0 / 1240.0 + te_balsa
L = ["# Wing rev B (foam blocks) - mass table", "",
     "Generated by `design/cad_revB/scripts/build_stage3.py` (volume x density for each modelled part). Raw rows: `mass_table.csv`.",
     "Densities (kg/m3): XPS 30, PLA 1240 (printed fill: LE 0.50, TE 0.85, keys 1.0), selected light sheet 90, light 100, medium 130, hard 160, "
     "carbon 1550, PETG 1270, steel 7850. Film 50 g/m2 on %.3f m2 (same as rev A). Glue 14 g estimate *(interp.)*: rev A 8 g + 4 g foam bonds + 2 g "
     "spray adhesive for film on foam." % C.film_area_m2(), "",
     "| Group | Parts | Material (density) | Mass g |", "|---|---|---|---|"]
for g, (n, m, mat) in grp.items():
    L.append("| %s | %d | %s | %.1f |" % (g, n, ", ".join(sorted(mat)), m))
L += ["| **Wing without servos** | | | **%.1f** |" % total,
      "| MG90S servos (2 x 13.4 g, datasheet value *(interp.)*) + arms | | | %.1f |" % servo,
      "| **Wing with servos** | | | **%.1f** |" % (total + servo), "",
      "## Variants (density substitution on the same geometry, not separate models)", "",
      "Empty mass = 440 g (rest of aircraft incl. 4 servos, A1 *(interp.)*) + wing without servos. Score = 996 x 100 / empty. "
      "Stall: rev A 8.86 m/s loaded (1593 g, rho 1.05, with tail download) x sqrt(mass ratio). R6: <= 9.0 m/s.", "",
      "| Wing | Mass g | vs rev A g | Empty g | Score | Score change | Loaded stall m/s | R6 |", "|---|---|---|---|---|---|---|---|",
      line("Rev A (reference)", REVA),
      line("**Rev B as modelled (PLA LE/TE)**", total),
      line("Rev B, ASA Aero 0.70 LE/TE *(interp. density)*", asa),
      line("Rev B, LW-PLA 0.55 LE/TE (fails heat: HDT 53 C)", lw),
      line("Rev B-lite: ASA Aero LE + hard balsa TE (x 250-280)", lite), "",
      "PLA in the model: %.1f g (LE %.1f g, TE %.1f g). Rev A balsa LE + TE: 11.2 g." % (pla, pla - te_pla, te_pla),
      "Uncertainty: XPS density +-15 %, printed fill +-20 %, film and glue +-5 g, balsa +-20 % between sheets."]
open(os.path.join(CAD, "mass_table.md"), "w").write("\n".join(L) + "\n")
print("variants: PLA %.1f  ASA %.1f  LW %.1f  lite %.1f" % (total, asa, lw, lite))

# ---- STEP, STL ----
objs = [o for o in d.Objects if o.TypeId == "Part::Feature" and not o.Name.startswith("TMP_")]
