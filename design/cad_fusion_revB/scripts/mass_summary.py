"""Mass table of the Fusion rev B model from check/bodies.json (written by check_model.py in Fusion).
Same densities and the same film / glue rules as the FreeCAD models, so the totals compare one to one:
  pod:  film 30 g/m2 on the outer skin (5.04 g, rev B value), glue + CA 10 % of the wood, 4 magnet pairs 3.36 g
  wing: film 50 g/m2 (29.2 g, rev A value), glue 8.0 g, M2 screws 1.2 g, CA hinges 0.8 g; servos 27.4 g
  tail: film 30 g/m2 both sides (4.85 g, rev A value), steel pushrod ends 1.6 g, guide clips (not modelled) 1.0 g
Reference (FreeCAD): pod 133.1 g (rev B, with hex lightening), wing 156.6 g, tail 78.1 g, empty aircraft 689 g.
Optimisation (P1/P2, design/optimisation/): one balsa stock 1.5 mm medium (0.14) and one birch ply 1.5 mm (0.65);
laminated parts are one body per layer piece (lam.py) and add lamination glue, 40 g/m2 dry per interface (estimate,
P1 - weigh a test laminate); the hex holes in the side laminate are filmed on the inner face too (30 g/m2)."""
import json
import math
import os
import re

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = json.load(open(os.path.join(BASE, "check", "bodies.json")))
WOOD = ("Balsa medium", "Balsa light", "Balsa hard", "Birch ply", "Lite-ply", "Birch dowel")
REF = {"Pod": 133.1, "Wing": 156.6, "Tail": 78.1}
EXTRA = {"Pod": [("covering film 30 g/m2 (outer skin)", 5.04), ("magnets 4 pairs D6x2", 3.36)],
         "Wing": [("covering film 50 g/m2", 29.2), ("glue (estimate)", 8.0), ("M2 hatch screws", 1.2), ("CA hinges", 0.8)],
         "Tail": [("covering film 30 g/m2, both sides", 4.85), ("steel pushrod ends", 1.6), ("guide clips (not modelled)", 1.0)]}


GLUE_LAM = 40.0e-6          # g/mm2 per lamination interface (estimate, P1_single_stock.md)
FILM_IN = 30.0e-6           # g/mm2, film on the inner face over the side holes


def lamination_glue(rs):
    """(n - 1) interfaces x face area for every laminated component (bodies named <part>-<layer><piece>)."""
    comps = {}
    for r in rs:
        m = re.match(r"^(.*)-(\d)([a-h]?)$", r.get("body", ""))
        if not m or m.group(1) != r["name"]:
            continue
        c = comps.setdefault(r["name"], [0, 0.0])
        c[0] = max(c[0], int(m.group(2)))
        c[1] += r["vol_mm3"]
    g = 0.0
    for n, (k, vol) in comps.items():
        if k > 1:
            g += (k - 1) * vol / (k * 1.5) * GLUE_LAM
    return g, len(comps)


def side_hole_film():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "hex_cells.json")
    if not os.path.exists(path):
        return 0.0, 0
    H = json.load(open(path))
    n, a = 0, 0.0
    for v in H.get("sides", {}).values():
        r = v["af"] / math.sqrt(3.0)
        n += len(v["cells"])
        a += len(v["cells"]) * 1.5 * math.sqrt(3.0) * r * r
    return a * FILM_IN, n


def group(grp):
    """bodies (no jigs, no lumped electronics), mass per material and the film / glue / hardware lines of one group."""
    rs = [r for r in rows if r["path"].split("/")[0] == grp and r["material"] != "Electronics (lumped)"
          and "Jigs" not in r["path"]]
    by_mat = {}
    for r in rs:
        by_mat.setdefault(r["material"], [0, 0.0])
        by_mat[r["material"]][0] += 1
        by_mat[r["material"]][1] += r["mass_g"]
    wood = sum(v[1] for m, v in by_mat.items() if m in WOOD)
    extra = list(EXTRA[grp])
    if grp == "Pod":
        extra.insert(1, ("glue + CA sealing, 10 % of the wood", 0.10 * wood))
        fh, nh = side_hole_film()
        if nh:
            extra.append(("film on the inner face over %d side holes" % nh, fh))
    gl, nl = lamination_glue(rs)
    if nl:
        extra.append(("lamination glue, %d laminated parts (estimate)" % nl, gl))
    return rs, by_mat, extra


def main():
    out = ["# Rev B (Fusion) - mass table", "",
           "Generated by `scripts/mass_summary.py` from `check/bodies.json` (body volumes from Fusion x density: "
           "balsa medium 0.14 (the one balsa stock, 1.5 mm), birch ply 0.65 (the one ply stock, 1.5 mm), PETG 1.27, "
           "carbon 1.55, steel 7.85, birch dowel 0.70 g/cm3; *interp.* until the sheets are weighed). Laminated parts "
           "(2-4 layers of 1.5 mm) add lamination glue at 40 g/m2 per interface *(estimate)*. Electronics and the "
           "reservoir are placeholders and are not summed here.", ""]
    summary = []
    for grp in ("Pod", "Wing", "Tail"):
        rs, by_mat, extra = group(grp)
        total = sum(v[1] for v in by_mat.values()) + sum(e[1] for e in extra)
        out += ["## %s" % grp, "", "| Material | Bodies | Mass g |", "|---|---|---|"]
        for m, (n, g) in sorted(by_mat.items(), key=lambda kv: -kv[1][1]):
            out.append("| %s | %d | %.1f |" % (m, n, g))
        for nm, g in extra:
            out.append("| %s | | %.1f |" % (nm, g))
        out += ["| **Total %s** | | **%.1f** |" % (grp.lower(), total), ""]
        heavy = sorted(rs, key=lambda r: -r["mass_g"])[:8]
        out.append("Heaviest bodies: " + ", ".join("%s %.1f g" % (r["name"], r["mass_g"]) for r in heavy))
        out.append("")
        summary.append((grp, total, REF[grp]))
    out += ["## Against the FreeCAD reference", "", "| Group | Fusion rev B | FreeCAD | Difference |", "|---|---|---|---|"]
    dsum = 0.0
    for grp, tot, ref in summary:
        out.append("| %s | %.1f g | %.1f g | %+.1f g |" % (grp, tot, ref, tot - ref))
        dsum += tot - ref
    out += ["| **Empty aircraft** | **%.0f g** | 689 g | %+.1f g |" % (689 + dsum, dsum), "",
            "Score = 996 x 100 / empty mass: %.1f (FreeCAD rev B: 144.5)." % (996 * 100 / (689 + dsum)), ""]
    import sys
    sys.path.insert(0, os.path.join(BASE, "..", "optimisation"))
    import p2_cg
    tot, mx, mz, _ = p2_cg.empty()
    out += ["## Empty aircraft, direct sum", "",
            "Every body of the model (no jigs), the electronics at their catalogue masses (design/FIXED_MASSES.md) "
            "and the film / glue lines above, summed by `design/optimisation/p2_cg.py`: **%.1f g, CG X %.1f mm**; "
            "score 996 x 100 / %.1f = **%.1f**. This is the number used from P3 on (the FreeCAD comparison above "
            "keeps the FreeCAD electronics / reservoir figures)." % (tot, mx / tot, tot, 99600.0 / tot), ""]
    open(os.path.join(BASE, "mass_table.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    for grp, tot, ref in summary:
        print("%-5s %.1f g (ref %.1f)" % (grp, tot, ref))
    print("empty %.0f g, score %.1f" % (689 + dsum, 996 * 100 / (689 + dsum)))


if __name__ == "__main__":
    main()
