"""Wing rev A - lift performance at the design air densities.
Writes design/aero/wing_lift_performance.md. Usage: python3 design/calc/wing_lift.py
All inputs are in INPUTS; values marked interp are estimates to correct with test data."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "aero", "wing_lift_performance.md")
G = 9.81
INPUTS = {
    "span_m": 0.990,
    "chord_m": 0.280,
    "CLmax_wing": 1.35,          # interp: 0.85 x SD7062 airfoil CLmax 1.58 (D-002)
    "mass_rest_kg": 0.440,       # interp: aircraft without the wing (brief A1)
    "mass_wing_kg": 0.1566,      # CAD rev A, without servos (design/cad/mass_table.md)
    "mass_water_kg": 0.996,      # 1000 mL at 28-30 C
    "tail_download_N": 1.0,      # interp: trim load at 13 m/s (D-001)
    "n_design": 6.0,             # limit 4 x safety factor 1.5 (D-004)
    "cruise_mps": 13.0,
}
SITES = [("Bengaluru (December tests)", 1.05), ("Chennai (January competition)", 1.15)]
SPEEDS = [8, 9, 10, 11, 12, 13, 15, 18, 20]


def run(p=INPUTS):
    S = p["span_m"] * p["chord_m"]
    m_empty = p["mass_rest_kg"] + p["mass_wing_kg"]
    m_load = m_empty + p["mass_water_kg"]
    W, We = m_load * G, m_empty * G
    Wt = W + p["tail_download_N"]
    CL = p["CLmax_wing"]
    L = []
    L += ["# Wing rev A — lift performance", "",
          "Generated by `design/calc/wing_lift.py`. Change the inputs in that file and run it again to update this page.", "",
          "## 1. Inputs", "",
          "| Item | Value | Source |", "|---|---|---|",
          "| Wing area S | %.4f m² (%.3f × %.3f m) | CAD rev A |" % (S, p["span_m"], p["chord_m"]),
          "| Wing CLmax | %.2f | *(interp.)* 0.85 × SD7062 airfoil CLmax 1.58 (D-002); not measured |" % CL,
          "| Air density | 1.05 kg/m³ Bengaluru, 1.15 kg/m³ Chennai | `design/01_weather_design_inputs.md` (design values: hot afternoon) |",
          "| Loaded mass | %.0f g → weight %.2f N | %.0f g aircraft *(interp.)* + %.1f g wing (CAD) + %.0f g water |"
          % (m_load * 1000, W, p["mass_rest_kg"] * 1000, p["mass_wing_kg"] * 1000, p["mass_water_kg"] * 1000),
          "| Empty mass (after the drop) | %.0f g → weight %.2f N | |" % (m_empty * 1000, We),
          "| Tail down-load at trim | %.1f N | *(interp.)* D-001 |" % p["tail_download_N"],
          "| Design load factor | %.0f | limit 4 × safety factor 1.5 (D-004) |" % p["n_design"], "",
          "Lift L = ½ ρ V² S CL. The lift increases with the square of the airspeed. In level flight the lift is equal to the weight "
          "(plus the tail down-load); the maximum lift at a given airspeed is at CLmax.", "",
          "## 2. Maximum lift (wing at CLmax)", "",
          "| Airspeed | " + " | ".join(s for s, _ in SITES) + " |", "|---|" + "---|" * len(SITES)]
    for V in SPEEDS:
        cells = []
        for _, rho in SITES:
            Lm = 0.5 * rho * V * V * S * CL
            cells.append("%.1f N (%.2f kgf)" % (Lm, Lm / G))
        L.append("| %d m/s | %s |" % (V, " | ".join(cells)))
    L += ["", "## 3. Lift coefficient needed for level flight", "",
          "| Airspeed | " + " | ".join("%s loaded | %s empty" % (s.split(" ")[0], s.split(" ")[0]) for s, _ in SITES) + " |",
          "|---|" + "---|---|" * len(SITES)]
    for V in SPEEDS:
        cells = []
        for _, rho in SITES:
            q = 0.5 * rho * V * V
            cells += ["%.2f" % (W / (q * S)), "%.2f" % (We / (q * S))]
        L.append("| %d m/s | %s |" % (V, " | ".join(cells)))
    L += ["", "A value above %.2f (CLmax) means the wing stalls at that airspeed." % CL, "",
          "## 4. Key speeds", "", "| Item | " + " | ".join(s for s, _ in SITES) + " |", "|---|" + "---|" * len(SITES)]
    rows = [
        ("Stall speed, loaded", lambda rho: (2 * W / (rho * S * CL)) ** 0.5),
        ("Stall speed, loaded, with the tail down-load", lambda rho: (2 * Wt / (rho * S * CL)) ** 0.5),
        ("Stall speed, empty (after the drop)", lambda rho: (2 * We / (rho * S * CL)) ** 0.5),
        ("Stall speed, loaded, if the wing CLmax is only 1.20", lambda rho: (2 * W / (rho * S * 1.20)) ** 0.5),
        ("Lowest airspeed for load factor %.0f at CLmax (manoeuvre speed)" % p["n_design"],
         lambda rho: (2 * p["n_design"] * W / (rho * S * CL)) ** 0.5),
    ]
    for name, f in rows:
        L.append("| %s | %s |" % (name, " | ".join("%.1f m/s" % f(rho) for _, rho in SITES)))
    q_c = [0.5 * rho * p["cruise_mps"] ** 2 for _, rho in SITES]
    L.append("| CL at %.0f m/s cruise, loaded / empty | %s |" % (p["cruise_mps"], " | ".join("%.2f / %.2f" % (W / (q * S), We / (q * S)) for q in q_c)))
    L += ["", "## 5. What the numbers mean", "",
          "- **Hand launch:** the throw must give more than the stall speed with the tail down-load "
          "(about %.1f m/s in Bengaluru and %.1f m/s in Chennai). Wind adds to the airspeed: launch into the 4–6 m/s afternoon wind."
          % ((2 * Wt / (1.05 * S * CL)) ** 0.5, (2 * Wt / (1.15 * S * CL)) ** 0.5),
          "- **Bengaluru is the more difficult case**, because its air is about 10 % less dense. If the aircraft launches well in the December tests, "
          "it also launches in Chennai.",
          "- **Cruise:** at %.0f m/s the loaded wing needs CL ≈ %.2f (Bengaluru) and %.2f (Chennai). This is in the low-drag range of the SD7062 "
          "(Cd ≈ 0.012–0.013 from CL 0.2 to 0.7). After the drop, the CL is low (≈ 0.2): the aircraft climbs or must fly slower."
          % (p["cruise_mps"], W / (q_c[0] * S), W / (q_c[1] * S)),
          "- **Structure:** below about %.0f m/s the wing stalls before it reaches load factor %.0f, so a gust or a pull-up at normal flight speeds "
          "cannot overload it (spar margin ≈ 4 at that load, D-004)." % (min((2 * p["n_design"] * W / (rho * S * CL)) ** 0.5 for _, rho in SITES), p["n_design"]),
          "- **Largest uncertainty: the wing CLmax.** If it is 1.20 instead of 1.35, every stall speed increases by about 6 %. "
          "Measure it with a throw test of a loaded dummy (brief Q6), then set `CLmax_wing` in `design/calc/wing_lift.py` and run it again.",
          "- **Cross-check:** a nonlinear lifting-line analysis with the SD7062 polars (`design/aero/wing_lift_performance.py` → "
          "`wing_lift_performance.txt`, separate session) gives a 3D CLmax of about 1.41–1.45 at Re 120k–180k, and 1.21–1.31 if the 2D CLmax "
          "is 11 % lower. Its loaded stall speed is 8.7 m/s (Bengaluru) and 8.35 m/s (Chennai). The value CLmax = 1.35 used here is between those cases.",
          "- These are wing-only values for steady flight. They do not include fuselage lift, ground effect, or the propeller slipstream."]
    open(OUT, "w").write("\n".join(L) + "\n")
    return OUT


if __name__ == "__main__":
    print(run())
